#!/bin/bash
# Builds the RCCL Inspector profiler plugin for ROCm, for the trainer's
# --rccl_inspector: $JAXTITAN_ROOT/lib/librccl-profiler-inspector.so.
#
# RCCL carries the Inspector's source (plugins/profiler/inspector, from NCCL)
# with a CUDA-only Makefile. Its only CUDA uses are cudaGetDevice and three
# driver calls it loads from libcuda.so (cuDeviceGet, cuDeviceGetUuid,
# cuGetErrorString), so this copies the source, maps those to HIP, and builds
# it with hipcc. Run inside the JAX-Titan container, with an RCCL source tree
# or a copy of its plugins/profiler/inspector directory where the container
# can read it:
#
#   bash scripts/build_rccl_inspector.sh [RCCL_OR_INSPECTOR_DIR]
set -euo pipefail

ROOT=${JAXTITAN_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)/.jaxtitan}
DIR=${1:-${RCCL_SRC:-$ROOT/src/rccl-inspector}}
if [ -f "$DIR/inspector.cc" ]; then SRC=$DIR; else SRC=$DIR/plugins/profiler/inspector; fi
RCCL=$SRC
BUILD=$ROOT/build/rccl-inspector
OUT=$ROOT/lib/librccl-profiler-inspector.so

[ -f "$SRC/inspector.cc" ] || { echo "no Inspector source in $SRC" >&2; exit 1; }
mkdir -p "$BUILD" "$ROOT/lib"
cp -r "$SRC"/*.cc "$SRC"/*.h "$SRC"/nccl "$BUILD"/

cat > "$BUILD/cuda_compat.h" <<'EOF'
// The CUDA names the Inspector uses, as HIP.
#pragma once
#include <hip/hip_runtime.h>
typedef hipError_t cudaError_t;
typedef hipError_t CUresult;
typedef hipDevice_t CUdevice;
typedef hipUUID CUuuid;
#define cudaSuccess hipSuccess
#define CUDA_SUCCESS hipSuccess
#define cudaGetDevice hipGetDevice
#define cudaGetErrorString hipGetErrorString
EOF

cd "$BUILD"
sed -i -e 's|#include <cuda.h>|#include "cuda_compat.h"|' \
       -e 's|#include <cuda_runtime.h>|#include "cuda_compat.h"|' ./*.cc ./*.h
sed -i -e 's|"libcuda.so"|"libamdhip64.so"|' -e 's|"libcuda.so.1"|"libamdhip64.so.7"|' \
       -e 's|"cuGetErrorString"|"hipDrvGetErrorString"|' \
       -e 's|"cuDeviceGetUuid"|"hipDeviceGetUuid"|' -e 's|"cuDeviceGet"|"hipDeviceGet"|' \
       inspector_cudawrap.cc
cat > version.cc <<EOF
// Generated by build_rccl_inspector.sh
extern "C" const char* get_git_version_info() {
  return "$(git -C "$RCCL" describe --always --dirty 2>/dev/null || echo unknown)-hip";
}
EOF

hipcc -std=c++17 -fPIC -O2 -D__HIP_PLATFORM_AMD__ -DNCCL_INSPECTOR_ENABLE_WARN=0 \
  -I. -Inccl -shared \
  inspector.cc inspector_json.cc inspector_prom.cc inspector_plugin.cc inspector_cudawrap.cc \
  inspector_ring.cc inspector_event_pool.cc json.cc version.cc \
  -ldl -lpthread -o "$OUT"
echo "built $OUT"
